import sys

def gen():
    print("#include \"../include/font.h\"")
    print("const uint8 font_8x16[95][16] = {")
    for c in range(32, 127):
        data = [0]*16
        if c == 32: pass
        elif 65 <= c <= 90: # A-Z (very blocky)
            data = [0x3C, 0x66, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x66, 0x00]*2 # stub
            # Actually I'll just use a pattern for all so it's not boxes
            data = [0x00, 0x00, 0x7E, 0x42, 0x42, 0x7E, 0x42, 0x42, 0x7E, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]
        else:
            data = [0x18, 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]

        # Real characters for some
        if c == 65: data = [0x18, 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x66, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]
        if c == 66: data = [0x7C, 0x66, 0x66, 0x7C, 0x66, 0x66, 0x7C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]
        if c == 62: data = [0x60, 0x30, 0x18, 0x0C, 0x18, 0x30, 0x60, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00] # >
        if c == 10: data = [0]*16

        line = ", ".join(hex(b) for b in data)
        print(f"    {{{line}}}, // '{chr(c)}'")
    print("};")

gen()
